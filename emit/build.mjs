#!/usr/bin/env node
/* ─────────────────────────────────────────────────────────────
   Foundation · Emitter

   Turns the Tailwind-flavoured token source (tokens/*.css, authored as
   `@theme` blocks) into Tailwind-free outputs that a self-contained
   artifact can consume directly:

     dist/tokens.inline.css  — flat :root {…} + [data-theme="dark"] {…},
                               paste into an artifact <style>. No build,
                               no Tailwind, CSP-safe.
     dist/tokens.json        — { light: {token: value}, dark: {…} } for
                               artifact JS (Canvas/WebGL series colors etc.).

   The ONLY transform for the CSS path is `@theme {`/`@theme static {`
   → `:root {`. Everything else (var(), color-mix, the dark block, the
   reduced-motion media query) is already plain CSS and passes through.

   Generated files — never hand-edit dist/. Re-run `pnpm build`.
   ───────────────────────────────────────────────────────────── */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");

// Order is readability-only; declarations merge regardless.
const LAYERS = [
  "palette",
  "surface",
  "typography",
  "elevation",
  "motion",
  "layout",
  "chart",
  "dark",
];

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\n{3,}/g, "\n\n");
const themeToRoot = (css) => css.replace(/@theme\s+static\s*\{/g, ":root {").replace(/@theme\s*\{/g, ":root {");

// ── 1. dist/tokens.inline.css ──────────────────────────────────
const header =
  "/* GENERATED by foundation/emit/build.mjs — DO NOT EDIT.\n" +
  "   Source of truth: foundation/tokens/*.css. Re-run `pnpm build`.\n" +
  "   Inline this whole block into a self-contained artifact's <style>. */\n\n";

const inlineCss =
  header +
  LAYERS.map((name) => themeToRoot(stripComments(readFileSync(join(root, "tokens", `${name}.css`), "utf8"))).trim())
    .filter(Boolean)
    .join("\n\n") +
  "\n";

mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, "tokens.inline.css"), inlineCss);

// ── 2. dist/tokens.json ────────────────────────────────────────
// Light = every --decl OUTSIDE the dark block and OUTSIDE @media.
// Dark  = every --decl inside dark.css's [data-theme="dark"] block.
const DECL = /--([\w-]+)\s*:\s*([^;{}]+);/g;
const collect = (css) => {
  const out = {};
  for (const [, name, value] of css.matchAll(DECL)) out[name] = value.trim().replace(/\s+/g, " ");
  return out;
};

const light = {};
for (const name of LAYERS) {
  if (name === "dark") continue;
  let css = stripComments(readFileSync(join(root, "tokens", `${name}.css`), "utf8"));
  // motion.css ends with a @media reduced-motion override — exclude it so the
  // light map keeps real durations, not the 0ms accessibility override.
  if (name === "motion") css = css.split("@media")[0];
  Object.assign(light, collect(css));
}
const dark = collect(stripComments(readFileSync(join(root, "tokens", "dark.css"), "utf8")));

writeFileSync(join(dist, "tokens.json"), JSON.stringify({ light, dark }, null, 2) + "\n");

const count = (o) => Object.keys(o).length;
console.log(`foundation: emitted dist/tokens.inline.css (${inlineCss.length} bytes)`);
console.log(`foundation: emitted dist/tokens.json (light ${count(light)} / dark ${count(dark)} tokens)`);
